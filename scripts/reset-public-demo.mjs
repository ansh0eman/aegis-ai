import Database from "better-sqlite3";
import { basename, resolve } from "node:path";

if (process.argv[2] !== "--confirm-public-demo-reset" || process.argv.length !== 3) {
  console.error("Usage: npm run db:reset-public-demo -- --confirm-public-demo-reset");
  process.exit(1);
}
if (process.env.AEGIS_PUBLIC_DEMO_DATABASE !== "true") {
  throw new Error("Refusing reset: AEGIS_PUBLIC_DEMO_DATABASE must equal true.");
}
if (!process.env.AEGIS_DATABASE_PATH || basename(process.env.AEGIS_DATABASE_PATH) !== "aegis-public-demo.db") {
  throw new Error("Refusing reset: AEGIS_DATABASE_PATH must explicitly end in aegis-public-demo.db.");
}
const database = new Database(resolve(process.cwd(), process.env.AEGIS_DATABASE_PATH));
database.pragma("foreign_keys = ON");

try {
  const identities = [
    { email: requiredEmail("PUBLIC_DEMO_ADMIN_EMAIL"), role: "admin" },
    { email: requiredEmail("PUBLIC_DEMO_USER1_EMAIL"), role: "member" },
    { email: requiredEmail("PUBLIC_DEMO_USER2_EMAIL"), role: "member" },
  ];
  if (new Set(identities.map(({ email }) => email)).size !== 3) {
    throw new Error("The configured demo email addresses must be distinct.");
  }
  const users = database.prepare("SELECT id, email FROM users ORDER BY id").all();
  const allowedEmails = new Set(identities.map(({ email }) => email));
  if (users.length !== 3 || users.some((user) => !allowedEmails.has(user.email))) {
    throw new Error("Refusing reset: database does not contain exactly the three configured demo accounts.");
  }

  const reset = database.transaction(() => {
    const userIds = users.map(({ id }) => id);
    const placeholders = userIds.map(() => "?").join(",");
    database.prepare(`DELETE FROM messages WHERE conversation_id IN (SELECT id FROM conversations WHERE user_id IN (${placeholders}))`).run(...userIds);
    database.prepare(`DELETE FROM conversations WHERE user_id IN (${placeholders})`).run(...userIds);
    database.prepare(`DELETE FROM ai_usage WHERE user_id IN (${placeholders})`).run(...userIds);
    database.prepare("DELETE FROM audit_logs").run();
    database.prepare("DELETE FROM demo_request_buckets").run();
    database.prepare(`DELETE FROM ai_policies WHERE user_id IN (${placeholders})`).run(...userIds);

    for (const identity of identities) {
      const user = users.find((candidate) => candidate.email === identity.email);
      database.prepare("UPDATE users SET role = ?, status = 'active' WHERE id = ?").run(identity.role, user.id);
      database.prepare(
        "INSERT INTO ai_policies (user_id, ai_enabled, max_prompt_chars, max_requests_per_day, created_at, updated_at) VALUES (?, 0, 1200, 20, ?, ?)",
      ).run(user.id, Date.now(), Date.now());
      seedSampleConversation(database, user.id, identity.role);
    }
  });
  reset();
  console.log("Reset only the explicitly configured public demo database: accounts active, roles restored, AI policies disabled, public usage limits cleared, and labeled sample conversations re-seeded.");
  console.log("Conversation, usage, and audit history was deleted. Passwords were preserved.");
} finally {
  database.close();
}

function requiredEmail(name) {
  const email = process.env[name]?.trim().toLowerCase();
  if (!email || email.length > 254 || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
    throw new Error(`Set ${name} before resetting the public demo.`);
  }
  return email;
}

function seedSampleConversation(database, userId, role) {
  const now = Date.now();
  const result = database.prepare("INSERT INTO conversations (user_id, created_at) VALUES (?, ?)").run(userId, now);
  const conversationId = Number(result.lastInsertRowid);
  const prompt = "Seeded sample: How does role-based access control work in this workspace?";
  const answer = role === "admin"
    ? "Seeded sample answer (not generated by AI): Admin-only routes check the signed-in user's role on the server. Member accounts can use their own conversations but cannot access user management or audit controls."
    : "Seeded sample answer (not generated by AI): Your conversation belongs to your account. The server checks ownership before loading or continuing it, while admin controls are restricted to the designated demo admin.";
  const insert = database.prepare("INSERT INTO messages (conversation_id, role, content, created_at) VALUES (?, ?, ?, ?)");
  insert.run(conversationId, "user", prompt, now);
  insert.run(conversationId, "assistant", answer, now + 1);
}
